/* ФиксАР — язык оболочки.
 *
 * Подключается ДО app.js: тот при запуске сразу рисует шапку и список дел, и
 * если словаря к этому мигу нет, первый кадр выйдет русским, а второй —
 * английским. Мигание языка человек читает как поломку.
 *
 * ── Почему словарь ключуется самой русской строкой ──────────────────────
 *
 * Обычный способ — выдуманные коды (`case.send`, `bell.all_read`) — потребовал
 * бы переименовать тысячу мест в app.js и держать в голове, что значит каждый
 * код. Здесь ключ — та самая русская фраза, что уже написана в коде:
 *
 *     T("Все прочитаны")  ->  "All read"
 *
 * Что это даёт:
 *   · русский остаётся в исходнике читаемым — код не превращается в россыпь
 *     кодов, а его и читают по-русски, как весь остальной проект;
 *   · пропущенный перевод показывает РУССКУЮ фразу, а не `case.send` посреди
 *     английского экрана. Дыра видна, но страница остаётся рабочей;
 *   · добавить язык — значит добавить файл словаря, не трогая app.js.
 *
 * Чем платим: одинаковые русские фразы в разных местах получают один перевод.
 * Для оболочки это верно почти всегда, а где неверно — фразу разводят по
 * смыслу прямо в исходнике (например, «Открыть» дела и «Открыть» документа).
 *
 * ── Почему переключение перезагружает страницу ──────────────────────────
 *
 * Надписи расставлены по всему app.js: часть лежит в DOM, часть собрана
 * склейкой в замыканиях, часть уже уехала в отрисованные сообщения. Обойти всё
 * это на лету нельзя — получился бы наполовину переведённый экран, а это хуже
 * обоих языков. Состояние (дело, токен, разложенные панели) переживает
 * перезагрузку по своим ключам, поэтому она обходится дёшево и честно.
 */
(function () {
  "use strict";

  var КЛЮЧ = "fixar.lang";
  var ЯЗЫКИ = ["ru", "en"];

  /* Выбор языка при первом заходе.
   *
   * Порядок: что человек выбрал руками -> что просит браузер -> русский.
   *
   * Русский последним намеренно: сервис русскоязычный, и для всех, кто пришёл
   * с русским браузером, ничего не меняется. Английский достаётся тому, у кого
   * браузер английский, — то есть тому, кому русская страница бесполезна.
   * Проверяем ВЕСЬ список navigator.languages, а не только первый: у многих
   * первым стоит язык интерфейса системы, а рабочий — вторым. */
  function определить() {
    var сохранённый = null;
    try { сохранённый = localStorage.getItem(КЛЮЧ); } catch (e) { /* приватный режим */ }
    if (ЯЗЫКИ.indexOf(сохранённый) >= 0) return сохранённый;

    var список = (navigator.languages && navigator.languages.length)
      ? navigator.languages
      : [navigator.language || ""];
    for (var i = 0; i < список.length; i++) {
      if (/^ru\b/i.test(String(список[i]))) return "ru";
    }
    return /^en\b/i.test(String(список[0] || "")) ? "en" : "ru";
  }

  var код = определить();

  /* Словарь подставляет lang-en.js. Его может не быть — тогда English молча
     вырождается в русский, а не в пустой экран: страница обязана работать,
     даже если файл словаря не доехал до хранилища. */
  function словарь() {
    return (код === "en" && window.СЛОВАРЬ_EN) ? window.СЛОВАРЬ_EN : null;
  }

  /* Чего не хватило — копим и показываем ОДНИМ списком по требованию.
     Ругаться в консоль на каждую пропущенную фразу значит утопить в шуме
     настоящие ошибки: непереведённых на первых порах будут сотни. */
  var пропущено = Object.create(null);

  function T(строка) {
    if (строка == null) return строка;
    var сл = словарь();
    if (!сл) return строка;
    var s = String(строка);
    if (Object.prototype.hasOwnProperty.call(сл, s)) return сл[s];
    /* Пустые и чисто служебные строки в словаре не нужны — не считаем их
       пропусками, иначе список утонет в разделителях и пробелах. */
    if (/[а-яА-ЯёЁ]/.test(s)) пропущено[s] = (пропущено[s] || 0) + 1;
    return строка;
  }

  /* ── Разметка страниц ────────────────────────────────────────────────
   *
   * Статический текст в HTML переводится не словарём, а парным свойством
   * рядом с самим текстом:
   *
   *     <span data-en="All read">Все прочитаны</span>
   *     <button title="Уведомления" data-en-title="Notifications">
   *
   * Так английский лежит ВОЗЛЕ русского: правя одно, видишь второе, и они не
   * разъезжаются. Для app.js это не годится — там текст рождается в коде, —
   * а для разметки годится лучше словаря.
   *
   * Свойства перечислены поимённо. Пройтись по всем `data-en-*` подряд было бы
   * короче, но тогда опечатка `data-en-titel` молча ничего не сделала бы. */
  var СВОЙСТВА = ["title", "placeholder", "aria-label", "alt", "content", "value"];

  function перевестиДерево(корень) {
    if (код !== "en" || !корень) return;
    var узлы = корень.querySelectorAll("[data-en]");
    for (var i = 0; i < узлы.length; i++) {
      узлы[i].textContent = узлы[i].getAttribute("data-en");
    }
    for (var s = 0; s < СВОЙСТВА.length; s++) {
      var имя = СВОЙСТВА[s];
      var список = корень.querySelectorAll("[data-en-" + имя + "]");
      for (var j = 0; j < список.length; j++) {
        список[j].setAttribute(имя, список[j].getAttribute("data-en-" + имя));
      }
    }
  }

  function выбрать(новый) {
    if (ЯЗЫКИ.indexOf(новый) < 0 || новый === код) return;
    try { localStorage.setItem(КЛЮЧ, новый); } catch (e) { /* приватный режим */ }
    location.reload();
  }

  /* Переключатель рисуем здесь, а не в разметке каждой страницы: страниц
     четыре, и три из них про язык ничего не знают. Кнопка показывает ТОТ
     ЯЗЫК, НА КОТОРЫЙ ПЕРЕЙДЁШЬ, а не текущий: «EN» на русской странице
     читается как действие, «RU» на русской — как состояние, и человек жмёт
     её впустую. */
  function поставитьПереключатель(место) {
    if (!место || document.getElementById("langswitch")) return null;
    var другой = (код === "ru") ? "en" : "ru";
    var к = document.createElement("button");
    к.id = "langswitch";
    к.type = "button";
    к.className = "lang";
    к.textContent = другой.toUpperCase();
    к.setAttribute("lang", другой);
    к.title = (код === "ru") ? "Switch to English" : "Переключить на русский";
    к.setAttribute("aria-label", к.title);
    к.addEventListener("click", function () { выбрать(другой); });
    место.appendChild(к);
    return к;
  }

  document.documentElement.setAttribute("lang", код);

  window.ЯЗЫК = {
    код: код,
    английский: код === "en",
    T: T,
    выбрать: выбрать,
    перевестиДерево: перевестиДерево,
    поставитьПереключатель: поставитьПереключатель,
    /* Для правки словаря: ЯЗЫК.пропущенные() в консоли отдаёт то, чего не
       хватило именно на пройденных экранах. Это честнее, чем сверять словарь
       с исходником: показывает не всё подряд, а то, что человек реально
       увидел по-русски. */
    пропущенные: function () {
      return Object.keys(пропущено).sort(function (a, b) {
        return пропущено[b] - пропущено[a];
      }).map(function (s) { return пропущено[s] + "x  " + s; });
    }
  };

  /* Разметку переводим, как только она есть. DOMContentLoaded, а не load:
     ждать картинок незачем, а до разбора разметки querySelectorAll ничего не
     найдёт. Если сценарий подключён в конце body, разметка уже готова —
     тогда работаем сразу, иначе кадр покажет русский поверх английского. */
  function приготовить() {
    перевестиДерево(document);
    /* Переключатель встаёт САМ в место с этим номером. Страница объявляет
       только «здесь», а как он выглядит и что делает — знает модуль: иначе
       четыре страницы держали бы четыре копии одной кнопки, и они разъехались
       бы при первой же правке. Нет места — нет кнопки, и это не ошибка:
       страница возврата после входа живёт полторы секунды, ей выбор языка ни
       к чему. */
    поставитьПереключатель(document.getElementById("langmount"));
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", приготовить);
  } else {
    приготовить();
  }
})();
