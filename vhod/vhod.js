/* ОБЩЕЕ ДЛЯ ЧЕТЫРЁХ ВХОДОВ: адрес службы, хранилище, вход, разговор с дверью.
   Каждая страница подключает этот файл и добавляет СВОЙ сценарий.

   ПОЧЕМУ ОДИН ФАЙЛ, А НЕ КОПИЯ В КАЖДОЙ СТРАНИЦЕ. Порядок входа (токен
   оболочки → свой прежний → анонимный) и ключи хранилища обязаны совпадать
   у всех четырёх: разойдутся — и один человек получит четыре учётки, а их у
   него и так бывало четыре. */
(function () {
  "use strict";

  "use strict";
  var API = "https://api.agrigate.pro";

  /* ФРАГМЕНТ — ТОЛЬКО ИЗ ФРАГМЕНТА, как у /podbor/: он не уходит на сервер и
     не оседает в журналах посредников. ?k= не поддерживается сознательно.

     ЧТО В НЁМ ЛЕЖИТ, РЕШАЕТ СТРАНИЦА, а не этот файл: у практика — ключ
     страницы, у передачи — код вещи, у поиска — запрос человека. Общая
     только добыча. */
  function фрагмент() {
    return (location.hash || "").replace(/^#\/?/, "").trim();
  }

  /* ХРАНИЛИЩЕ — РОВНО ТЕ ЖЕ КЛЮЧИ, ЧТО У /start/. Дверь, заведи она свой,
     подарила бы человеку ЕЩЁ одного субъекта — а их у одного человека и так
     бывало четыре. `fixar.token` принадлежит оболочке: читаем, не пишем. */
  var КЛЮЧ_ОБОЛОЧКИ = "fixar.token";
  var КЛЮЧ_СВОЙ = "fixar.start.token";

  var state = { token: "", кто: null, пакеты: null };

  function хранилище(к) {
    try { return localStorage.getItem(к) || ""; } catch (e) { return ""; }
  }

  function эл(id) { return document.getElementById(id); }

  function сказать(текст, беда) {
    var m = эл("micro");
    if (!m) return;
    m.textContent = текст || "";
    m.className = "micro" + (беда ? " bad" : "");
  }

  async function api(путь, тело) {
    var r = await fetch(API + путь, {
      method: "POST",
      headers: state.token
        ? { "Content-Type": "application/json",
            "Authorization": "Bearer " + state.token }
        : { "Content-Type": "application/json" },
      body: JSON.stringify(тело || {})
    });
    var текст = await r.text();
    var д = null;
    try { д = текст ? JSON.parse(текст) : null; } catch (e) { д = null; }
    if (!r.ok) {
      var e2 = new Error((д && д.detail && (д.detail.message || д.detail)) ||
                         ("отказ " + r.status));
      e2.код = r.status;
      throw e2;
    }
    return д;
  }

  /* МЕТКА ДВЕРИ. Каждая страница называет СЕБЯ, а не общее «vhod».
     Метка уезжает в `channel_bindings.label` и остаётся там навсегда — по
     ней и только по ней потом видно, какой дверью человек вошёл. Общая
     метка на четыре двери означала бы, что воронку по входам построить
     нельзя вовсе: доля пришедших по ссылке практика и доля пришедших из
     поиска слились бы в одно число.

     Умолчание оставлено на случай, если страница забудет назваться: лучше
     неразличимый вход, чем отказ входа. */
  /* КЛЮЧ СТРАНИЦЫ ПРАКТИКА уходит в заведение, чтобы площадка знала, КТО
     привёл человека (схема долей 12.09.2026). Только при заведении: у того,
     кто уже входил на этом устройстве, запись давно лежит, и чужая ссылка её
     не перепишет — ни здесь, ни в базе. */
  async function вход(метка, ключ_страницы) {
    var чужой = хранилище(КЛЮЧ_ОБОЛОЧКИ);
    if (чужой) { state.token = чужой; return; }
    var мой = хранилище(КЛЮЧ_СВОЙ);
    if (мой) { state.token = мой; return; }
    var тело = { label: метка || "vhod" };
    if (ключ_страницы) тело.page_key = String(ключ_страницы).slice(0, 64);
    var нов = await api("/entry/anon", тело);
    state.token = нов.token;
    try { localStorage.setItem(КЛЮЧ_СВОЙ, нов.token); } catch (e) { /* сессия */ }
  }

  async function пакеты() {
    if (state.пакеты) return state.пакеты;
    try {
      var r = await fetch(API + "/packs");
      var д = await r.json();
      state.пакеты = {};
      ((д && д.packs) || []).forEach(function (п) {
        state.пакеты[п.id] = п.title || п.id;
      });
    } catch (e) { state.пакеты = {}; }
    return state.пакеты;
  }

  /* Наружу — ровно то, что нужно сценариям страниц. */
  window.ДВЕРЬ = { api: api, вход: вход, эл: эл, сказать: сказать,
                   пакеты: пакеты, фрагмент: фрагмент,
                   state: state, API: API };
})();
